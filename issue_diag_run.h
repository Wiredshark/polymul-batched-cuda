#pragma once
// Round 25: exit-time tensor-core issue patterns (int8 IMMA k32/k16 alone, with LDS.64 B fragments, with IMAD/IADD 1:1 and 1:3, one vs two accumulator chains, P2 hot-loop mix alone and +IMMA 1:3) at 1/4/8 warps per SMSP. Exit-time issue-pattern diag (FHERMA_ISSUE_DIAG=0: off). Loads precompiled sm_120 cubins (issue_diag.h, generated by
// reorder/gen_diag.py: tl.py template loop whose body is overwritten with crafted / transplanted instruction words), times each
// at 1 and 8 warps per SMSP with per-warp clock64, prints cycles per instruction per SMSP as JSON lines next to the issue model's
// prediction and the local RTX 5070 measurement. Never touches the production module, streams or buffers.
#include "issue_diag.h"
#include <cuda.h>
#include <cstdio>
#include <cstdlib>
#include <vector>
#include <map>
#include <algorithm>
#include <chrono>
template<class C> void run_issue_diag(C& d){
    if(const char* e=std::getenv("FHERMA_ISSUE_DIAG"))if(std::atoi(e)==0)return;
    const auto t0=std::chrono::steady_clock::now();
    auto attr=d.driver.template get<decltype(&::cuDeviceGetAttribute)>("cuDeviceGetAttribute");
    auto occf=d.driver.template get<decltype(&::cuOccupancyMaxActiveBlocksPerMultiprocessor)>("cuOccupancyMaxActiveBlocksPerMultiprocessor");
    auto fattr=d.driver.template get<decltype(&::cuFuncGetAttribute)>("cuFuncGetAttribute");
    auto dname=d.driver.template get<decltype(&::cuDeviceGetName)>("cuDeviceGetName");
    auto dver=d.driver.template get<decltype(&::cuDriverGetVersion)>("cuDriverGetVersion");
    CUdevice dev=0;if(d.cuDeviceGet(&dev,0)!=CUDA_SUCCESS)return;
    int mj=0,mn=0,sms=0,clk=0,drv=0;char name[128]={0};
    attr(&mj,CU_DEVICE_ATTRIBUTE_COMPUTE_CAPABILITY_MAJOR,dev);attr(&mn,CU_DEVICE_ATTRIBUTE_COMPUTE_CAPABILITY_MINOR,dev);
    attr(&sms,CU_DEVICE_ATTRIBUTE_MULTIPROCESSOR_COUNT,dev);attr(&clk,CU_DEVICE_ATTRIBUTE_CLOCK_RATE,dev);dname(name,127,dev);dver(&drv);
    for(char* c=name;*c;++c)if(*c=='"'||*c=='\\')*c='_';
    const unsigned npat=sizeof(ISSUE_PATS)/sizeof(ISSUE_PATS[0]);
    std::printf("{\"diag\":\"issue\",\"k\":\"info\",\"dev\":\"%s\",\"cc\":\"%d.%d\",\"sms\":%d,\"clock_khz\":%d,\"driver\":%d,\"npat\":%u}\n",name,mj,mn,sms,clk,drv,npat);std::fflush(stdout);
    if(mj!=12||mn!=0){std::printf("{\"diag\":\"issue\",\"k\":\"skip\",\"why\":\"not sm_120\"}\n");std::fflush(stdout);return;}
    if(d.cuCtxSynchronize()!=CUDA_SUCCESS)return;
    const unsigned maxw=8;CUdeviceptr out=0,clkb=0;const size_t nclk=size_t(sms)*maxw*4*3;
    if(d.cuMemAlloc(&out,1u<<16)!=CUDA_SUCCESS)return;
    if(d.cuMemAlloc(&clkb,nclk*8)!=CUDA_SUCCESS){d.cuMemFree(out);return;}
    std::vector<unsigned long long> h(nclk);
    for(unsigned p=0;p<npat;++p){
        const IssuePat& P=ISSUE_PATS[p];
        CUmodule mod=nullptr;CUresult r=d.cuModuleLoadData(&mod,P.cubin);
        if(r!=CUDA_SUCCESS){std::printf("{\"diag\":\"issue\",\"p\":\"%s\",\"error\":\"load %d\"}\n",P.name,int(r));std::fflush(stdout);continue;}
        CUfunction f=nullptr;if(d.cuModuleGetFunction(&f,mod,"tl_t")!=CUDA_SUCCESS){d.cuModuleUnload(mod);continue;}
        int regs=0,occ=0;fattr(&regs,CU_FUNC_ATTRIBUTE_NUM_REGS,f);occf(&occ,f,128,0);
        for(unsigned wi=0;wi<3;++wi){const unsigned w=wi==0?1u:wi==1?4u:8u;
            const unsigned bps=std::min<unsigned>(w,unsigned(occ>0?occ:1)),nb=unsigned(sms)*bps;unsigned rep=P.rep,k=7;
            void* args[]={&out,&rep,&clkb,&k};double best=0;bool bad=false;
            for(int t=0;t<3&&!bad;++t){
                if(d.cuLaunchKernel(f,nb,1,1,128,1,1,0,nullptr,args,nullptr)!=CUDA_SUCCESS||d.cuCtxSynchronize()!=CUDA_SUCCESS){bad=true;break;}
                d.cuMemcpyDtoH(h.data(),clkb,size_t(nb)*4*3*8);
                std::map<unsigned long long,std::vector<std::pair<unsigned long long,unsigned long long>>> per;
                for(unsigned g=0;g<nb*4;++g)per[h[3*g]].push_back({h[3*g+1],h[3*g+2]});
                std::vector<double> v;
                for(auto& kv:per){unsigned long long s=~0ull,e=0;for(auto& x:kv.second){s=std::min(s,x.first);e=std::max(e,x.second);}
                    if(e>s)v.push_back(double(kv.second.size())*rep*P.nloop/double(e-s)/4.0);}
                if(v.empty())continue;std::sort(v.begin(),v.end());best=std::max(best,v[v.size()/2]);}
            if(bad){std::printf("{\"diag\":\"issue\",\"p\":\"%s\",\"w\":%u,\"error\":\"launch\"}\n",P.name,w);std::fflush(stdout);break;}
            std::printf("{\"diag\":\"issue\",\"p\":\"%s\",\"w\":%u,\"wps\":%u,\"regs\":%d,\"nloop\":%u,\"cpi\":%.4f,\"local5070_cpi\":%.4f}\n",
                P.name,w,bps,regs,P.nloop,best>0?1.0/best:-1.0,P.local_cpi[wi]);std::fflush(stdout);}
        d.cuModuleUnload(mod);}
    d.cuMemFree(out);d.cuMemFree(clkb);
    std::printf("{\"diag\":\"issue\",\"k\":\"done\",\"s\":%.2f}\n",std::chrono::duration<double>(std::chrono::steady_clock::now()-t0).count());std::fflush(stdout);
}
